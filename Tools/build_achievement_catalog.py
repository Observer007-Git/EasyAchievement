#!/usr/bin/env python3
"""Build the in-game achievement catalog from matching-build DB2 CSVs."""

import argparse
import csv
from collections import defaultdict
from pathlib import Path


def read_csv(path):
    with path.open(encoding="utf-8-sig", newline="") as stream:
        return {int(row["ID"]): row for row in csv.DictReader(stream)}


def number(value):
    return int(value or 0)


def lua_string(value):
    result = ['"']
    for char in value or "":
        code = ord(char)
        if char == '"' or char == "\\":
            result.append("\\" + char)
        elif code < 32 or code == 127:
            result.append(f"\\{code:03d}")
        else:
            result.append(char)
    result.append('"')
    return "".join(result)


def build(input_dir, output, build_version):
    achievements = read_csv(input_dir / "enUS" / "Achievement.csv")
    categories = read_csv(input_dir / "enUS" / "Achievement_Category.csv")
    for achievement in achievements.values():
        if number(achievement["Category"]) not in categories:
            raise ValueError(f"Missing category for achievement {achievement['ID']}")
    for category in categories.values():
        parent = number(category["Parent"])
        if parent != -1 and parent not in categories:
            raise ValueError(f"Missing parent for category {category['ID']}")
    excluded_roots = {1, 15076}  # Statistics and guild achievements.
    def root(category_id):
        while number(categories[category_id]["Parent"]) != -1:
            category_id = number(categories[category_id]["Parent"])
        return category_id
    categories = {
        category_id: row for category_id, row in categories.items()
        if root(category_id) not in excluded_roots
    }
    achievements = {
        achievement_id: row for achievement_id, row in achievements.items()
        if number(row["Category"]) in categories
    }
    totals = defaultdict(lambda: [0, 0])
    for achievement in achievements.values():
        category_total = totals[number(achievement["Category"])]
        category_total[0] += 1
        category_total[1] += number(achievement["Points"])

    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write("local _, Addon = ...\n")
        stream.write("-- Generated by Tools/update_reward_database.sh; do not edit.\n")
        stream.write("Addon.AchievementCatalogData={schema=2,build=")
        stream.write(lua_string(build_version) + ",categories={\n")
        for category_id in sorted(categories):
            category = categories[category_id]
            values = [number(category["Parent"]),
                      number(category["Ui_order"]),
                      *totals[category_id]]
            stream.write(f"[{category_id}]={{{','.join(map(str, values))}}},\n")
        stream.write("},achievements={\n")
        for achievement_id in sorted(achievements):
            achievement = achievements[achievement_id]
            values = [number(achievement["Category"]),
                      number(achievement["Points"]),
                      number(achievement["Faction"]),
                      number(achievement["Ui_order"]),
                      number(achievement["IconFileID"])]
            stream.write(f"[{achievement_id}]={{{','.join(map(str, values))}}},\n")
        stream.write("}}\n")
    print(f"catalog achievements={len(achievements)} "
          f"categories={len(categories)}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--build", required=True)
    args = parser.parse_args()
    build(args.input, args.output, args.build)
